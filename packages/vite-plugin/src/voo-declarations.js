import { writeFileSync } from "node:fs";

export function writeVooDeclarations(components, framework) {
  for (const component of components) {
    if (component.format !== "source") continue;
    const declaration = generateVooDeclaration(component, framework);
    writeFileSync(component.id.replace(/\.voo$/, ".d.voo.ts"), declaration);
  }
}

export function generateVooDeclaration(component, framework) {
  if (framework === "react") return generateReactDeclaration(component);
  if (framework !== "vue") throw new Error(`Unknown Vooya framework "${framework}".`);
  return generateVueDeclaration(component);
}

function generateVueDeclaration(component) {
  const props = component.props
    .map(
      (prop) =>
        `  ${propertyName(prop.name)}${prop.required ? "" : "?"}: ${typescriptType(prop.rustType)};`,
    )
    .join("\n");
  const events = component.events
    .map((event) => {
      const parameters = event.parameters
        .map((parameter) => `${parameter.name}: ${typescriptType(parameter.rustType)}`)
        .join(", ");
      return `  ${propertyName(event.name)}: (${parameters}) => void;`;
    })
    .join("\n");

  return `// Generated by @vooya/vite-plugin. Do not edit.
import type { ComponentOptionsMixin, DefineComponent } from "vue";

interface ${component.name}Props {
${props}
}

interface ${component.name}Events {
${events}
  error: (error: { stage: "load" | "mount"; cause: unknown }) => void;
}

declare const component: DefineComponent<
  ${component.name}Props,
  {},
  {},
  {},
  {},
  ComponentOptionsMixin,
  ComponentOptionsMixin,
  ${component.name}Events
>;

export default component;
`;
}

function generateReactDeclaration(component) {
  const props = component.props
    .map(
      (prop) =>
        `  ${propertyName(prop.name)}${prop.required ? "" : "?"}: ${typescriptType(prop.rustType)};`,
    )
    .join("\n");
  const events = component.events
    .map((event) => {
      const parameters = event.parameters
        .map((parameter) => `${parameter.name}: ${typescriptType(parameter.rustType)}`)
        .join(", ");
      return `  ${reactEventName(event.name)}?: (${parameters}) => void;`;
    })
    .join("\n");

  return `// Generated by @vooya/vite-plugin. Do not edit.
import type { ComponentType } from "react";

interface ${component.name}Props {
${props}
${events}
  onError?: (error: { stage: "load" | "mount"; cause: unknown }) => void;
  className?: string;
}

declare const component: ComponentType<${component.name}Props>;

export default component;
`;
}

function typescriptType(rustType) {
  if (/^(?:[iu](?:8|16|32|64|128|size)|f(?:32|64))$/.test(rustType)) return "number";
  if (rustType === "bool") return "boolean";
  if (rustType === "String" || rustType === "str" || rustType === "&str") return "string";
  throw new Error(`Unsupported Voo contract type "${rustType}".`);
}

function propertyName(name) {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
}

function reactEventName(name) {
  const pascal = name
    .split(/[-_]/)
    .filter(Boolean)
    .map((part) => `${part[0].toUpperCase()}${part.slice(1)}`)
    .join("");
  return `on${pascal}`;
}
